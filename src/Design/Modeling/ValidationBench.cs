// The testbenches validation generates (brief-modelcomposer-11 R-mc11-4). Each is ordinary .cnl text — "show testbench"
// writes it out, and `circuitrf hb` (or dc, sparam, lp) runs it unchanged — so what was simulated is inspectable.
//
// The device is the exported .cmodel as a ComposedFet at its base finger count (a ComposedCore for data stated at the
// intrinsic plane). Bias is applied at the device plane: through ideal voltage sources for DC, ideal tees (1 H, 1 F) for
// S-parameters as the multi-bias data was taken, and a power source and a Tuner with their own bias tees for large signal,
// each harmonic terminated as the data states (a harmonic not stated is shorted). Ambient is `temp`.

using System.Globalization;
using System.Numerics;
using System.Text;

namespace CircuitRF.Design.Modeling;

internal static class ValidationBench
{
    /// <summary>The impedance a shorted harmonic is given — the Tuner's own <c>Zdefault</c>.</summary>
    internal const double Short = 1e-6;

    /// <summary>An open harmonic: far above any device impedance, and finite for the linear solve.</summary>
    internal const double Open = 1e6;

    internal static string R(double v) => v.ToString("R", CultureInfo.InvariantCulture);

    /// <summary>A complex impedance as a value with no spaces (an unquoted value must contain none).</summary>
    internal static string Z(Complex z) =>
        z.Imaginary == 0 ? R(z.Real) : $"{R(z.Real)}{(z.Imaginary < 0 ? "-" : "+")}j*{R(Math.Abs(z.Imaginary))}";

    private static string Header(string what, string set) =>
        $"; Model Composer validation — {what}, data set '{set}'\n; generated by circuitRF; the model is the .cmodel named below\n\n";

    /// <summary>The device line: a ComposedFet on (g, d, s) at the model's base fingers, or the intrinsic core alone.</summary>
    internal static string Device(string modelPath, int n, bool intrinsic, string g, string d, string s = "0") =>
        $"{(intrinsic ? "ComposedCore" : "ComposedFet")}:X1 {g} {d} {s} File=\"{modelPath.Replace('\\', '/')}\" N={n}\n";

    /// <summary>DC at one bias: the terminal currents through probes.</summary>
    internal static string Dc(string set, string device, double ambientC, double vgs, double vds)
    {
        var sb = new StringBuilder(Header("DC I–V", set));
        sb.Append($"temp = {R(ambientC)}\nVgs = {R(vgs)}\nVds = {R(vds)}\n\n");
        sb.Append("Vdc:VG vg 0 V=Vgs\nIProbe:IPG vg g\n").Append(device).Append("IProbe:IPD vd d\nVdc:VD vd 0 V=Vds\n\n");
        sb.Append("analysis DC1 type=dc\n");
        return sb.ToString();
    }

    /// <summary>S-parameters at one bias through ideal tees, ports at <paramref name="z0"/>. A non-uniform axis is written
    /// as its span and count, and validation runs the data's own frequencies.</summary>
    internal static string SParams(string set, string device, double ambientC, double vgs, double vds, double[] f, double z0)
    {
        var sb = new StringBuilder(Header("S-parameters", set));
        sb.Append($"temp = {R(ambientC)}\nVgs = {R(vgs)}\nVds = {R(vds)}\n\n");
        sb.Append("Vdc:VG vg 0 V=Vgs\nIProbe:IPG vg lg\nL:LG lg g L=1\nC:CG pa g C=1\n");
        sb.Append($"Port:P1 pa 0 Num=1 Z={R(z0)} Ohm\n").Append(device);
        sb.Append("Vdc:VD vd 0 V=Vds\nIProbe:IPD vd ld\nL:LD ld d L=1\nC:CD pb d C=1\n");
        sb.Append($"Port:P2 pb 0 Num=2 Z={R(z0)} Ohm\n\n");
        sb.Append($"analysis SP1 type=sparam start={R(f[0])} stop={R(f[^1])} npts={f.Length}\n");
        return sb.ToString();
    }

    /// <summary>The harmonic keys of a termination: <c>Z[1]</c> the fundamental, <c>Z[k]</c> each stated harmonic.</summary>
    private static string Harmonics(Complex fundamental, IReadOnlyList<Complex> harmonics, int maxHarm)
    {
        var sb = new StringBuilder($"Z[1]={Z(fundamental)}");
        for (int k = 2; k <= maxHarm; k++)
            sb.Append($" Z[{k}]={Z(k - 2 < harmonics.Count ? harmonics[k - 2] : Short)}");
        return sb.Append($" Zdefault={R(Short)}").ToString();
    }

    /// <summary>
    /// A single-tone power sweep: an available-power source behind the source terminations and a gate tee, the load a
    /// Tuner with its own drain tee, probes at both device terminals; the HB analysis wrapped in a sweep over <c>Pin</c>
    /// (dBm). <c>circuitrf hb</c> runs it as written.
    /// </summary>
    internal static string PowerSweep(string set, string device, double ambientC, LargeSignalConditions c, double[] pin, int maxHarm)
    {
        var sb = new StringBuilder(Header("power sweep", set));
        sb.Append($"temp = {R(ambientC)}\nf0 = {R(c.FrequencyHz!.Value)}\nVgs = {R(c.Vgs!.Value)}\nVds = {R(c.Vds!.Value)}\nPin = {R(pin[0])}\n\n");
        sb.Append($"P1Tone:PS ps 0 Pavl=Pin dBm Freq=f0 {Harmonics(c.SourceZ ?? 50, c.SourceHarmonics, maxHarm)}\n");
        sb.Append("C:CG ps g C=1\nVdc:VG vg 0 V=Vgs\nL:LG vg g L=1\nIProbe:IPG g gx\n");
        sb.Append(device);
        sb.Append($"IProbe:IPD dx ld\nTuner:TL ld 0 {Harmonics(c.LoadZ ?? 50, c.LoadHarmonics, maxHarm)} BiasTee=on Vbias=Vds\n\n");
        sb.Append($"analysis HB1 type=hb Tone=f0 MaxHarm={maxHarm}\n");
        sb.Append($"analysis SW1 type=parametric_sweep Var=Pin Values={string.Join(",", pin.Select(R))} Inner=HB1\n");
        return sb.ToString();
    }

    /// <summary>Two equal tones <see cref="LargeSignalConditions.SpacingHz"/> apart about the centre, each at <c>Pin</c>.</summary>
    internal static string TwoTone(string set, string device, double ambientC, LargeSignalConditions c, double[] pin, int maxHarm)
    {
        double f0 = c.FrequencyHz!.Value, df = c.SpacingHz!.Value;
        var sb = new StringBuilder(Header("two-tone", set));
        sb.Append($"temp = {R(ambientC)}\nf1 = {R(f0 - df / 2)}\nf2 = {R(f0 + df / 2)}\nVgs = {R(c.Vgs!.Value)}\nVds = {R(c.Vds!.Value)}\nPin = {R(pin[0])}\n\n");
        string zs = Harmonics(c.SourceZ ?? 50, c.SourceHarmonics, maxHarm).Replace("Zdefault", "Z");
        sb.Append($"PnTone:PS ps 0 Freq[1]=f1 Pavl[1]=Pin dBm Freq[2]=f2 Pavl[2]=Pin dBm {zs}\n");
        sb.Append("C:CG ps g C=1\nVdc:VG vg 0 V=Vgs\nL:LG vg g L=1\nIProbe:IPG g gx\n");
        sb.Append(device);
        sb.Append($"IProbe:IPD dx ld\nTuner:TL ld 0 {Harmonics(c.LoadZ ?? 50, c.LoadHarmonics, maxHarm)} BiasTee=on Vbias=Vds\n\n");
        sb.Append($"analysis HB1 type=hb NumFreqs=2 Tone[1]=f1 Tone[2]=f2 MaxHarm={maxHarm} MaxMixOrder={Math.Max(5, maxHarm)}\n");
        sb.Append($"analysis SW1 type=parametric_sweep Var=Pin Values={string.Join(",", pin.Select(R))} Inner=HB1\n");
        return sb.ToString();
    }
}
